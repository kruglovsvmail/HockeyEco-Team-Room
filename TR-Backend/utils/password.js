import crypto from 'crypto';

// Минимальная длина пароля, задаваемого пользователем. Жёстких требований по составу
// (цифры, регистр, спецсимволы) намеренно нет: аудитория — тренеры и родители, а не
// системные администраторы, и сложные правила они обходят предсказуемо, дописывая "1"
// в конец. Длину защищает лимит попыток входа, а не запреты в форме.
export const MIN_PASSWORD_LENGTH = 6;

// Временные пароли вида JH-3513: две латинские заглавные, дефис, четыре цифры.
//
// Буквы без I и O — их путают с единицей и нулём. Ровно поэтому цифры оставлены все
// десять: двусмысленных пар в наборе больше не осталось, а выбрасывать 0 и 1 значило бы
// урезать пространство перебора вчетверо ради несуществующей проблемы.
//
// Дефис — только для читаемости при диктовке по телефону; стойкости он не добавляет,
// потому что стоит всегда на одном месте.
//
// 24 × 24 × 10⁴ = 5 760 000 комбинаций. Против лимита в 10 попыток за 15 минут (960 в
// сутки) это порядка шестнадцати лет на полный перебор одного аккаунта.
const LETTERS = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
const LETTERS_COUNT = 2;
const DIGITS_COUNT = 4;

/**
 * Равномерный случайный индекс от 0 до max-1.
 *
 * Простой `% max` смещает распределение: 256 не делится нацело ни на 24, ни на 10,
 * поэтому младшие значения выпадали бы чаще. Отбраковываем хвост, который не укладывается
 * в целое число полных проходов — оставшийся диапазон делится ровно.
 */
const randomIndex = (max) => {
  const limit = 256 - (256 % max);
  let byte;
  do {
    byte = crypto.randomBytes(1)[0];
  } while (byte >= limit);
  return byte % max;
};

/**
 * Временный пароль для активации аккаунта и восстановления доступа.
 *
 * Раньше здесь было `Math.floor(1000 + Math.random() * 9000)` — девять тысяч вариантов
 * и предсказуемый генератор, которые вместе с отсутствием лимита входа перебирались за
 * четверть часа.
 */
export const generateTempPassword = () => {
  let letters = '';
  for (let i = 0; i < LETTERS_COUNT; i++) {
    letters += LETTERS[randomIndex(LETTERS.length)];
  }

  let digits = '';
  for (let i = 0; i < DIGITS_COUNT; i++) {
    digits += randomIndex(10);
  }

  return `${letters}-${digits}`;
};

/**
 * Проверка пароля, который пользователь задаёт себе сам.
 * Возвращает текст ошибки или null, если всё в порядке.
 */
export const validatePassword = (password) => {
  const value = String(password ?? '');
  if (value.length < MIN_PASSWORD_LENGTH) {
    return `Пароль должен содержать минимум ${MIN_PASSWORD_LENGTH} символов`;
  }
  return null;
};
