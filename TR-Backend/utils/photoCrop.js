// =============================================================================
// КАДРИРОВАНИЕ ФОТО В КВАДРАТ — серверная копия правил
//
// В приложениях (TR, LMS, ТФХ — utils/photoCrop.js) фото в квадратной рамке
// показывает браузер с object-fit: cover, а портретный кадр подрезается сверху
// по PHOTO_CROP_RULES, чтобы не срезать макушку. Картинку состава собирает сервер
// (services/formationImageService.js) — без браузера, поэтому те же правила здесь
// пересчитаны в прямоугольник, который вырезается из самого фото.
//
// Правила обязаны совпадать с фронтовыми: меняешь таблицу там — поменяй и здесь,
// иначе на картинке состава лица встанут не так, как в приложении. После правки
// подними TEMPLATE_VERSION в formationImageTemplate.js, чтобы уже собранные
// картинки пересобрались.
// =============================================================================

export const PHOTO_CROP_RULES = [
  // ширина/высота: от minRatio (включительно) до maxRatio (не включительно);
  // top — сколько процентов высоты фото срезать сверху.
  { label: 'узкие портреты, уже 7:10 (например, 2:3)', minRatio: 0,    maxRatio: 0.70, top: 10 },
  { label: 'портреты от 7:10 до 5:6 (3:4, 4:5 и т.п.)', minRatio: 0.70, maxRatio: 0.85, top: 5  },
  // Почти квадрат (шире 5:6), квадрат и альбомные кадры — правила нет:
  // кадрируется по центру, как в браузере.
];

/**
 * Квадрат, который показал бы браузер: { left, top, size } в пикселях фото.
 * Портрет — во всю ширину; сверху срезается по правилу (но не больше, чем не
 * влезло), остаток — снизу. Без правила и у альбомных кадров — по центру.
 */
export function getPhotoCropBox(width, height) {
  const size = Math.min(width, height);
  if (width >= height) {
    return { left: Math.floor((width - size) / 2), top: 0, size };
  }
  const overflow = height - size;
  const rule = PHOTO_CROP_RULES.find(r => width / height >= r.minRatio && width / height < r.maxRatio);
  const top = rule ? Math.min(Math.round(height * rule.top / 100), overflow) : Math.floor(overflow / 2);
  return { left: 0, top, size };
}
